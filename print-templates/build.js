#!/usr/bin/env node
/* Builds the two published print templates from the sources in this
   folder:
     /print-template.html            Player List
     /print-template-allinnings.html Field by Inning
   Each output is one self-contained file (fonts + logo inlined) because
   the iOS app (LineupPrintService) fetches it, fills the tokens and
   snapshots it a moment after load; nothing may load late. The web app
   fetches the same files for its printouts.

   Run from the repo root after editing anything here:
     node print-templates/build.js                                      */
const fs = require('fs');
const path = require('path');

const here = __dirname;
const root = path.join(here, '..');
const read = (f) => fs.readFileSync(path.join(here, f), 'utf8');
const font = (file, family, weight) =>
  `@font-face{font-family:"${family}";font-style:normal;font-weight:${weight};font-display:swap;` +
  `src:url(data:font/woff2;base64,${fs.readFileSync(path.join(here, 'fonts', file)).toString('base64')}) format("woff2")}`;

const fonts = [
  font('sofia-sans-extra-condensed-latin-900-normal.woff2', 'Sofia Sans Extra Condensed', 900),
  font('barlow-semi-condensed-latin-600-normal.woff2', 'Barlow Semi Condensed', 600),
  font('barlow-semi-condensed-latin-700-normal.woff2', 'Barlow Semi Condensed', 700),
].join('\n');

const logo = read('logo-ink.svg').trim()
  .replace(/<metadata>[\s\S]*?<\/metadata>/g, '')   // provenance blocks some tools add
  .replace(/ xmlns:c2pa="[^"]*"/, '')
  .replace(/^<svg /, '<svg aria-hidden="true" focusable="false" ')
  .replace(/>\s+</g, '><');
const css = read('print.css');
const finish = read('finish.js');

// Page rules live apart from #lo-css: the web app injects #lo-css into
// its own document and keeps its own @page and body.
const pageCss = `@page{size:letter landscape;margin:.45in}
html,body{margin:0;padding:0;background:#FAF6EB}
html.lo-paper,html.lo-paper body{background:#FFFFFF}
@media print{html,body{background:#FFFFFF}}`;

function page(title, bodyFile) {
  const body = read(bodyFile).trim().replace('@@LOGO@@', logo);
  for (const t of ['{{GAME}}', '{{OPPONENT}}', '{{DATE}}', '{{FIELD}}']) {
    if (!body.includes(t)) throw new Error(bodyFile + ' is missing ' + t);
  }
  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex">
<title>${title}</title>
<!-- Leadoff printout. GENERATED by print-templates/build.js: edit the
     sources in print-templates/ and rebuild. The iOS app fetches this
     file and fills its tokens; the web app reuses #lo-css, the
     .lo-print markup and #lo-finish. Keep the token names unchanged. -->
<style id="lo-fonts">
${fonts}
</style>
<style id="lo-page">
${pageCss}
</style>
<style id="lo-css">
${css}</style>
</head>
<body class="lo-doc">
${body}
<script id="lo-finish">
${finish}</script>
</body>
</html>
`;
}

const outputs = [
  ['print-template.html', page('Leadoff lineup card', 'list.html'), '{{TBODY}}'],
  ['print-template-allinnings.html', page('Leadoff field by inning', 'allinnings.html'), '{{CARDS}}'],
];
for (const [file, html, sanity] of outputs) {
  if (!html.includes(sanity)) throw new Error(file + ' lost ' + sanity + ' (iOS rejects the template without it)');
  fs.writeFileSync(path.join(root, file), html);
  console.log('wrote', file, (html.length / 1024).toFixed(1) + ' KB');
}
